#!/usr/bin/env python3
# finalize.py — ставит обложку и описание на видео Анны и присылает тексты в бот.
# Видео — то, что Анна обработала сама (CuAcjA0lWr4). Обложка — вариант 1
# (thumbs/thumb1.jpg, «ЧТО ТАКОЕ СВОБОДА»). Если видео недоступно через API
# (не на этом канале) — просто присылаем тексты в бот, Анна поставит сама.

import os

import tg
import yt_ops

VID = os.environ.get("FINAL_VIDEO_ID", "CuAcjA0lWr4")
THUMB = "thumbs/thumb1.jpg"

TITLE = "Что такое свобода"

DESCRIPTION = """Свобода — это не когда можно всё. Это когда тебе больше нечего доказывать.

Я долго путала свободу с побегом. Меняла города, работу, людей — а внутри оставалось то же кольцо. Пока не увидела простую вещь: я бегу не от обстоятельств, а от одной мысли, которую боюсь додумать до конца.

Это видео — про то, как свобода выглядит изнутри. Не громкие слова, а тихий момент, когда перестаёшь торговаться с собой. Про циклы, которые мы ходим по кругу, и про ту точку, где круг наконец размыкается.

Если ты хоть раз ловила себя на том, что вроде бы свободна, но всё равно не дышишь полной грудью — посмотри до конца.

А свобода для тебя — это состояние или всё-таки разрешение себе?

#свобода #осознанность #регрессология #выходтишины"""


def main():
    # Всегда шлём тексты в бот — чтобы у Анны были под рукой.
    tg.send_message("ЗАГОЛОВОК видео:\n\n" + TITLE)
    tg.send_message("ОПИСАНИЕ под видео (можно копировать целиком):\n\n" + DESCRIPTION)

    # Пытаемся поставить обложку и описание прямо на видео.
    try:
        yt = yt_ops.yt_auth.get_service()
        r = yt.videos().list(part="snippet", id=VID).execute()
        items = r.get("items")
        if not items:
            tg.send_message(
                f"Видео {VID} через API не открылось (возможно, оно не на подключённом канале). "
                "Обложку и описание поставь сама — тексты выше."
            )
            return
        sn = items[0]["snippet"]
        sn["description"] = DESCRIPTION
        yt.videos().update(part="snippet", body={"id": VID, "snippet": sn}).execute()
        print("описание обновлено")
        if os.path.exists(THUMB):
            yt_ops.set_thumbnail(VID, THUMB)
            print("обложка поставлена")
        tg.send_message("Готово: поставил на видео обложку «ЧТО ТАКОЕ СВОБОДА» и это описание.")
    except Exception as e:
        tg.send_message(
            f"Описание/обложку автоматически поставить не вышло ({e}). Тексты выше — поставь сама, "
            "это быстро в YouTube Studio."
        )
        print("finalize error:", e)


if __name__ == "__main__":
    main()
